    private void limparFormulario() {
        idSelecionado = -1;
        com.mycompany.atividade12.util.Combos.limpar(comboAtleta);
        com.mycompany.atividade12.util.Combos.limpar(comboCategoria);
        com.mycompany.atividade12.util.Combos.limpar(comboCampeonato);
        tabelaInscricao.clearSelection();
    }

    private void configurarTabela() {
        modeloTabela = new javax.swing.table.DefaultTableModel(
                new Object[]{"ID", "Atleta", "Categoria", "Campeonato"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelaInscricao.setModel(modeloTabela);
        tabelaInscricao.getSelectionModel().addListSelectionListener(e -> preencherFormulario());
    }

    private void carregarCombos() {
        try {
            com.mycompany.atividade12.util.Combos.carregar(comboAtleta, atletaDao.listarTodos());
            com.mycompany.atividade12.util.Combos.carregar(comboCategoria, categoriaDao.listarTodos());
            com.mycompany.atividade12.util.Combos.carregar(comboCampeonato, campeonatoDao.listarTodos());
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            listaAtual = dao.listarTodos();
            for (com.mycompany.atividade12.model.Inscricao inscricao : listaAtual) {
                modeloTabela.addRow(new Object[]{
                    inscricao.getId(), inscricao.getAtletaNome(),
                    inscricao.getCategoriaNome(), inscricao.getCampeonatoNome()
                });
            }
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }

    private void preencherFormulario() {
        int linha = tabelaInscricao.getSelectedRow();
        if (linha >= 0) {
            com.mycompany.atividade12.model.Inscricao inscricao = listaAtual.get(linha);
            idSelecionado = inscricao.getId();
            selecionarAtletaNoCombo(inscricao.getAtletaId());
            selecionarCategoriaNoCombo(inscricao.getCategoriaId());
            selecionarCampeonatoNoCombo(inscricao.getCampeonatoId());
        }
    }

    private void selecionarAtletaNoCombo(int id) {
        for (int i = 0; i < comboAtleta.getItemCount(); i++) {
            Object item = comboAtleta.getItemAt(i);
            com.mycompany.atividade12.model.Atleta atleta = (com.mycompany.atividade12.model.Atleta) item;
            if (atleta.getId() == id) {
                comboAtleta.setSelectedIndex(i);
                return;
            }
        }
    }

    private void selecionarCategoriaNoCombo(int id) {
        for (int i = 0; i < comboCategoria.getItemCount(); i++) {
            Object item = comboCategoria.getItemAt(i);
            com.mycompany.atividade12.model.Categoria categoria = (com.mycompany.atividade12.model.Categoria) item;
            if (categoria.getId() == id) {
                comboCategoria.setSelectedIndex(i);
                return;
            }
        }
    }

    private void selecionarCampeonatoNoCombo(int id) {
        for (int i = 0; i < comboCampeonato.getItemCount(); i++) {
            Object item = comboCampeonato.getItemAt(i);
            com.mycompany.atividade12.model.Campeonato campeonato = (com.mycompany.atividade12.model.Campeonato) item;
            if (campeonato.getId() == id) {
                comboCampeonato.setSelectedIndex(i);
                return;
            }
        }
    }
    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Object atletaSelecionado = comboAtleta.getSelectedItem();
        Object categoriaSelecionada = comboCategoria.getSelectedItem();
        Object campeonatoSelecionado = comboCampeonato.getSelectedItem();
        if (atletaSelecionado == null || categoriaSelecionada == null || campeonatoSelecionado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione o atleta, a categoria e o campeonato.");
            return;
        }
        try {
            com.mycompany.atividade12.model.Inscricao inscricao = new com.mycompany.atividade12.model.Inscricao();
            inscricao.setId(idSelecionado);
            inscricao.setAtletaId(((com.mycompany.atividade12.model.Atleta) atletaSelecionado).getId());
            inscricao.setCategoriaId(((com.mycompany.atividade12.model.Categoria) categoriaSelecionada).getId());
            inscricao.setCampeonatoId(((com.mycompany.atividade12.model.Campeonato) campeonatoSelecionado).getId());
            if (idSelecionado == -1) {
                dao.inserir(inscricao);
            } else {
                dao.atualizar(inscricao);
            }
            carregarTabela();
            limparFormulario();
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma inscrição na tabela.");
            return;
        }
        try {
            dao.excluir(idSelecionado);
            carregarTabela();
            limparFormulario();
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

