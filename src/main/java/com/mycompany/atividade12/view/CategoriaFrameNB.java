    private void limparFormulario() {
        idSelecionado = -1;
        campoNome.setText("");
        campoFaixa.setText("");
        campoPesoMin.setText("");
        campoPesoMax.setText("");
        tabelaCategoria.clearSelection();
    }

    private void configurarTabela() {
        modeloTabela = new javax.swing.table.DefaultTableModel(
                new Object[]{"ID", "Nome", "Faixa", "Peso mín.", "Peso máx."}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tabelaCategoria.setModel(modeloTabela);
        tabelaCategoria.getSelectionModel().addListSelectionListener(e -> preencherFormulario());
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            listaAtual = dao.listarTodos();
            for (com.mycompany.atividade12.model.Categoria categoria : listaAtual) {
                modeloTabela.addRow(new Object[]{
                    categoria.getId(), categoria.getNome(), categoria.getFaixa(),
                    Formatacao.mostrarDecimal(categoria.getPesoMin()), Formatacao.mostrarDecimal(categoria.getPesoMax())
                });
            }
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }

    private void preencherFormulario() {
        int linha = tabelaCategoria.getSelectedRow();
        if (linha >= 0) {
            com.mycompany.atividade12.model.Categoria categoria = listaAtual.get(linha);
            idSelecionado = categoria.getId();
            campoNome.setText(categoria.getNome());
            campoFaixa.setText(categoria.getFaixa());
            campoPesoMin.setText(Formatacao.mostrarDecimal(categoria.getPesoMin()));
            campoPesoMax.setText(Formatacao.mostrarDecimal(categoria.getPesoMax()));
        }
    }
