private final com.mycompany.atividade12.dao.AtletaDAO dao = new com.mycompany.atividade12.dao.AtletaDAO();
private final com.mycompany.atividade12.dao.AcademiaDAO academiaDao = new com.mycompany.atividade12.dao.AcademiaDAOJdbc();
private javax.swing.table.DefaultTableModel modeloTabela;
private java.util.List<com.mycompany.atividade12.model.Atleta> listaAtual;
private int idSelecionado = -1;

    private void limparFormulario() {
        idSelecionado = -1;
        campoNome.setText("");
        campoNasc.setText("");
        campoFaixa.setText("");
        campoPeso.setText("");
        com.mycompany.atividade12.util.Combos.limpar(comboAcademia);
        tabelaAtleta.clearSelection();
    }

private void configurarTabela() {
    modeloTabela = new javax.swing.table.DefaultTableModel(
            new Object[]{"ID", "Nome", "Nascimento", "Faixa", "Peso", "Academia"}, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    tabelaAtleta.setModel(modeloTabela);
    tabelaAtleta.getSelectionModel().addListSelectionListener(e -> preencherFormulario());
}

    private void carregarAcademias() {
        try {
            java.util.List<com.mycompany.atividade12.model.Academia> academias = academiaDao.listarTodos();
            com.mycompany.atividade12.util.Combos.carregar(comboAcademia, academias);
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }

    private void carregarTabela() {
        modeloTabela.setRowCount(0);
        try {
            listaAtual = dao.listarTodos();
            for (com.mycompany.atividade12.model.Atleta atleta : listaAtual) {
                modeloTabela.addRow(new Object[]{
                    atleta.getId(), atleta.getNome(), atleta.getDataNasc().format(Formatacao.DATA_BR),
                    atleta.getFaixa(), Formatacao.mostrarDecimal(atleta.getPeso()), atleta.getAcademiaNome()
                });
            }
        } catch (java.sql.SQLException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, com.mycompany.atividade12.util.ErrosBanco.traduzir(ex));
        }
    }

    private void preencherFormulario() {
        int linha = tabelaAtleta.getSelectedRow();
        if (linha >= 0) {
            com.mycompany.atividade12.model.Atleta atleta = listaAtual.get(linha);
            idSelecionado = atleta.getId();
            campoNome.setText(atleta.getNome());
            campoNasc.setText(atleta.getDataNasc().format(Formatacao.DATA_BR));
            campoFaixa.setText(atleta.getFaixa());
            campoPeso.setText(Formatacao.mostrarDecimal(atleta.getPeso()));
            for (int i = 0; i < comboAcademia.getItemCount(); i++) {
                Object itemAtual = comboAcademia.getItemAt(i);
                com.mycompany.atividade12.model.Academia academiaDoItem
                        = (com.mycompany.atividade12.model.Academia) itemAtual;
                if (academiaDoItem.getId() == atleta.getAcademiaId()) {
                    comboAcademia.setSelectedIndex(i);
                    break;
                }
            }
        }
    }
